export const DEFAULT_FONT_ID = 'caveat';

export function getFontById(id) {
  return LYRICS_FONTS.find((f) => f.id === id) || LYRICS_FONTS[4]; // Default to Caveat
}

let googleFontsLoaded = false;

/**
 * Dynamically injects Google Fonts link into document head once requested.
 */
export function ensureGoogleFontsLoaded() {
  if (typeof document === 'undefined' || googleFontsLoaded) return;
  const existing = document.getElementById('vynl-lyrics-google-fonts');
  if (existing) {
    googleFontsLoaded = true;
    return;
  }

  const families = LYRICS_FONTS.map((f) => `family=${f.googleParam}`).join('&');
  const url = `https://fonts.googleapis.com/css2?${families}&display=swap`;

  const link = document.createElement('link');
  link.id = 'vynl-lyrics-google-fonts';
  link.rel = 'stylesheet';
  link.href = url;
  document.head.appendChild(link);
  googleFontsLoaded = true;
}
